Import("env")

from datetime import datetime
from pathlib import Path
import re


def read_define(contents, name):
    match = re.search(
        r"^\s*#define\s+" + re.escape(name) + r"\s+(\d+)\s*$",
        contents,
        re.MULTILINE,
    )
    if match is None:
        raise ValueError("Missing or invalid {} in src/version.h".format(name))
    return int(match.group(1))


project_dir = Path(env.subst("$PROJECT_DIR"))
build_dir = Path(env.subst("$BUILD_DIR"))
version_header = project_dir / "src" / "version.h"
contents = version_header.read_text(encoding="utf-8")

major = read_define(contents, "VERSION_MAJOR")
minor = read_define(contents, "VERSION_MINOR")
patch = read_define(contents, "VERSION_PATCH")
build = read_define(contents, "VERSION_BUILD") + 1
build_time = datetime.now().astimezone()
date = build_time.strftime("%Y-%m-%d")
time = build_time.strftime("%H:%M:%S")
version = "{}.{}.{}.{}".format(major, minor, patch, build)
version_contents = (
    "#define VERSION_MAJOR {}\n"
    "#define VERSION_MINOR {}\n"
    "#define VERSION_PATCH {}\n"
    "\n"
    "// Generated by scripts/increment-version.py for this build; do not edit.\n"
    "// Copied to src/version.h only after a successful firmware build.\n"
    "#define VERSION_BUILD {}\n"
    '#define VERSION_DATE "{}"\n'
    '#define VERSION_TIME "{}"\n'
    '#define VERSION "{}"\n'
    '#define VERSION_STR "{} ({} {})"\n'
).format(major, minor, patch, build, date, time, version, version, date, time)

generated_include_dir = build_dir / "generated-version"
generated_include_dir.mkdir(parents=True, exist_ok=True)
generated_header = generated_include_dir / "build_version.h"
generated_header.write_text(
    version_contents,
    encoding="utf-8",
)

# The angle-bracket include lets this build-only header override src/version.h.
# The source header stays unchanged until the firmware and post-build actions succeed.
env.Prepend(CPPPATH=[str(generated_include_dir)])
env["VERSION_HEADER_SOURCE"] = str(version_header)
env["VERSION_HEADER_CANDIDATE"] = str(generated_header)